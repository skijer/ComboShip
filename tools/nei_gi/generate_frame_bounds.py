def number(value):
    return f'{value:.9f}f'

def row(directory):
    slug=directory.name
    points=[tuple(int(v.get(axis)) for axis in ('X','Y','Z'))
            for path in sorted(directory.glob('mesh_*_vtx')) for v in ET.parse(path).getroot()]
    assert points, slug
    words=struct.unpack_from('<16I',(directory/'scale_mtx').read_bytes(),64)
    # Signed integer half and unsigned fractional half of the actual N64 Mtx.
    def element(i):
        half=(words[i//2] >> (16 if i%2==0 else 0)) & 65535
        fraction=(words[8+i//2] >> (16 if i%2==0 else 0)) & 65535
        return (half if half<32768 else half-65536) + fraction/65536
    m=[element(i) for i in range(16)]
    assert all(m[i]==0 for i in (1,2,3,4,6,7,8,9,11,12,13,14)), slug
    assert m[0]==m[5]==m[10] and m[0]>0 and m[15]==1, slug
    scaled=[tuple(v*m[0] for v in p) for p in points]
    low=', '.join(number(min(p[i] for p in scaled)) for i in range(3))
    high=', '.join(number(max(p[i] for p in scaled)) for i in range(3))
    width=number(2*max(math.hypot(p[0],p[2]) for p in scaled))
    fit=preferred.get(slug,'{}' if slug in plain else '{ .85f, 14.f }')
    return f'{{ "{slug}", {{ {low} }}, {{ {high} }}, {width}, Kind::{effects.get(slug,"Neutral")}, {fit} }},'

def generate():
    bundled=sorted(d for d in ASSETS.iterdir() if d.is_dir())
    assert len(bundled)==63
    optional=OPTIONAL/'cojiro'
    rows=[row(d) for d in bundled]
    if optional.exists():
        rows.append(row(optional))
    return '// Generated by tools/nei_gi/generate_frame_bounds.py; serialized OPA + XLU bounds.\n'+'\n'.join(rows)+'\n'

if __name__=='__main__':
    TARGET.write_text(generate())
