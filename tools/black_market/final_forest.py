#!/usr/bin/env python3
"""Port the immutable FINAL forest into the existing private solo scene slots.

Physical art and scrolling parameters stay intact. Only resource identities,
engine-specific scene/actor framing and native camera settings are adapted.
The previous POC2 remains an immutable header/title donor.
"""
import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys
import xml.etree.ElementTree as ET
import zipfile

import forest
import poster_texture
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'lost_woods_entrance'))
import final_scene_segments as segments

FINAL_SHA = '4bef56b0b4e3fbe89308c85e29eefbfce19b4f91d21a7ed79fc5c3c519c4a7ef'
LEGACY_SHA = '3d45015fa43997e2f3a96440e018a6668a2b37d654bc3e32843c0f9100093cfb'
SOURCE_SCENE = 'alt/scenes/nonmq/Z2_LOST_WOODS/Z2_LOST_WOODS'
COLLISION = 'alt/scenes/nonmq/Z2_LOST_WOODS/Z2_LOST_WOODSCollisionHeader_005DF8'
ANIMATION_TARGET = 'custom/skiejer_forest/final_texanim'
MARKER = 'custom/skiejer_forest/final_scroll_v1'
PRIVATE = forest.PRIVATE


def sha(data):
    return hashlib.sha256(data).hexdigest()


def private_path(path):
    path = path.removeprefix('alt/')
    if path.startswith(forest.OLD):
        return path.replace(forest.OLD, PRIVATE, 1)
    if path.startswith('custom/prelude/Z2_LOST_WOODS/'):
        return path.replace('custom/prelude/Z2_LOST_WOODS/', PRIVATE + 'prelude/', 1)
    raise ValueError(f'outside final art dependency closure: {path}')


def crc64(path):
    value = 0xFFFFFFFFFFFFFFFF
    for byte in path.encode():
        value ^= byte << 56
        for _ in range(8):
            value = ((value << 1) ^ (0x42F0E1EBA9EA3693 if value >> 63 else 0)) & 0xFFFFFFFFFFFFFFFF
    return value


def scroll_bindings(data):
    segments.animation_segments(data, ANIMATION_TARGET)
    count, = struct.unpack_from('<I', data, 64)
    offset, result = 68, []
    for _ in range(count):
        segment, kind = struct.unpack_from('<bh', data, offset)
        offset += 3
        layers = []
        for _ in range(2 if kind == 1 else 1):
            x, y, width, height = struct.unpack_from('<bbBB', data, offset)
            offset += 4
            layers.append({'x': x, 'y': -y, 'width': width, 'height': height})
        result.append({'segment': abs(segment) + 7, 'layers': layers})
    return result


def scroll_header(bindings):
    rows = []
    for binding in bindings:
        layers = binding['layers'] + ([{'x': 0, 'y': 0, 'width': 0, 'height': 0}] if len(binding['layers']) == 1 else [])
        rows.append(f"    // Segment 0x{binding['segment']:02X}")
        rows.append('    { ' + str(binding['segment']) + ', ' + str(len(binding['layers'])) + ', { ' +
                    ', '.join('{ ' + ', '.join(str(layer[k]) for k in ('x', 'y', 'width', 'height')) + ' }' for layer in layers) + ' } },')
    return ('#pragma once\n#include <stdint.h>\n'
            '// Generated from FINAL TexAnim by tools/black_market/final_forest.py.\n'
            '// Native MM negates serialized Y velocity; these values already match it.\n'
            'namespace SoloForestScroll {\n'
            'struct Layer {\n    int8_t x, y;\n    uint8_t width, height;\n};\n'
            'struct Binding {\n    uint8_t segment, count;\n    Layer layers[2];\n};\n'
            'inline constexpr Binding kBindings[] = {\n' + '\n'.join(rows) + '\n};\n'
            f'inline constexpr const char* kMarker = "{MARKER}";\n'
            '} // namespace SoloForestScroll\n')


def resource_header(resources):
    return ('#pragma once\n// Generated by tools/black_market/final_forest.py; dependency-closed FINAL solo addon.\n'
            'static constexpr const char* kSoloForestResources[] = {\n' +
            ''.join(f'    "{path}",\n' for path in sorted(resources)) + '};\n')


def packed_art(data, path, mapping, hashes, bound):
    result, refs, calls = bytearray(data), [], 0
    for offset, w0, w1, opcode in segments._commands(data, path):
        if opcode in segments.EXPANDED:
            hi, lo = struct.unpack_from('<II', data, offset + 8)
            old_path = hashes.get((hi << 32) | lo)
            if old_path not in mapping:
                raise ValueError(f'{path}+{offset}: unresolved resource hash')
            target = mapping[old_path]
            new_hash = crc64(target)
            struct.pack_into('<II', result, offset + 8, new_hash >> 32, new_hash & 0xFFFFFFFF)
            refs.append(target)
        elif opcode == 0xDE:
            if w1 >> 24 not in bound or not w1 & 1 or w1 & 0x00FFFFFE:
                raise ValueError(f'{path}+{offset}: unresolved native scroll target')
            calls += 1
    return bytes(result), refs, calls


def transition_rows(data, oot):
    count, = struct.unpack_from('<I', data)
    if count != 2:
        raise ValueError('FINAL must retain its tunnel and exactly one authored shop door')
    result = bytearray(data)
    for index in range(count):
        offset = 4 + index * 16
        sides = struct.unpack_from('<4b', data, offset)
        actor, x, y, z, yaw, params = struct.unpack_from('<HhhhhH', data, offset + 4)
        if (index == 0 and (actor != 24 or sides != (1, -1, 0, -1))) or (index == 1 and (actor != 5 or sides != (0, -1, 0, -1))):
            raise ValueError('unexpected FINAL transition actor framing')
        if oot:
            angle = int(((yaw >> 7) & 0x1FF) * 65536 / 360)
            angle = ((angle + 32768) & 65535) - 32768
            struct.pack_into('<HhhhhH', result, offset + 4, 0x23 if index == 0 else 9, x, y, z,
                             angle, 0x100 if index == 0 else 0)
    return bytes(result)


def room_header(source, oot):
    commands = forest.native_commands(source)
    reader = forest.Reader(b'\0' * 64 + commands[10])
    mesh = reader.take('4B')
    opaque, translucent = private_path(reader.text()), private_path(reader.text())
    actors, raw = [], commands[1]
    for index in range(struct.unpack_from('<I', raw)[0]):
        row = list(struct.unpack_from('<HhhhhhhH', raw, 4 + index * 16))
        if row[0] in (0xD, 0x191, 0x192) or (oot and row[0] != 0xB3):
            continue
        if oot:
            row[0], row[4], row[5], row[6] = 0x151, 0, 0, 0
        actors.append(struct.pack('<HhhhhhhH', *row))
    return forest.scene([
        forest.command(22, commands[22]),
        forest.command(8, struct.pack('<bi', 0, 0) if oot else commands[8]),
        forest.command(18, commands[18]), forest.command(16, bytes([255, 255, 0])),
        forest.command(10, bytes(mesh) + forest.string(opaque) + forest.string(translucent)),
        forest.command(11, struct.pack('<I', 0)),
        forest.command(1, struct.pack('<I', len(actors)) + b''.join(actors)), forest.command(20)])


def convert(final, legacy):
    final, legacy = Path(final), Path(legacy)
    if sha(final.read_bytes()) != FINAL_SHA or sha(legacy.read_bytes()) != LEGACY_SHA:
        raise ValueError('immutable FINAL / previous solo input identity changed')
    resources, copied, refs, calls = {}, [], [], 0
    with zipfile.ZipFile(final) as source, zipfile.ZipFile(legacy) as previous:
        if source.testzip() or previous.testzip():
            raise ValueError('bad input CRC')
        art = [name for name in source.namelist() if name.startswith('custom/')]
        mapping = {name: private_path(name) for name in art}
        if len(set(mapping.values())) != len(mapping):
            raise ValueError('private path collision')
        hashes = {crc64(name): name for name in art}
        bound = segments.animation_segments(source.read(segments.ANIMATION_PATH), segments.ANIMATION_PATH)
        for name in art:
            data = original = source.read(name)
            target = mapping[name]
            if data.startswith(b'<DisplayList'):
                tree = ET.fromstring(data)
                for node in tree:
                    if 'Path' in node.attrib:
                        node.set('Path', private_path(node.get('Path')))
                        refs.append(node.get('Path'))
                data = ET.tostring(tree, encoding='utf-8')
            elif data[4:8] == b'TLDO':
                data, dependencies, count = packed_art(data, name, mapping, hashes, bound)
                refs.extend(dependencies)
                calls += count
            if name == poster_texture.RESOURCE:
                data = poster_texture.texture(original)
            resources[target] = data
            copied.append({'source': name, 'target': target, 'source_sha256': sha(original), 'sha256': sha(data)})
        top = forest.native_commands(source.read(SOURCE_SCENE))
        collision, cameras = forest.playable_collision(source.read(COLLISION))
        for oot, prefix in [(False, forest.MM), (True, forest.OOT)]:
            # POC2's stable native spawn, exits, BGM and special-file framing
            # remain intact; physical lights/collision/room art come from FINAL.
            commands = forest.native_commands(previous.read(prefix))
            commands[14] = transition_rows(top[14], oot)
            commands[15] = top[15]
            if not oot:
                commands = {key: value for key, value in commands.items() if key != 20}
                commands[26] = forest.string(ANIMATION_TARGET)
                commands[20] = b''
            resources[prefix] = forest.scene([forest.command(key, value) for key, value in commands.items()])
            resources[prefix + '_collision'] = collision
            for room in range(2):
                resources[prefix + '_room_' + str(room)] = room_header(source.read(SOURCE_SCENE + f'_room_0{room}'), oot)
        resources[PRIVATE + 'title'] = previous.read(PRIVATE + 'title')
        resources[ANIMATION_TARGET] = source.read(segments.ANIMATION_PATH)
        resources[MARKER] = b'FINAL native scrolling v1\n'
        missing = sorted(set(refs) - resources.keys())
        if missing:
            raise ValueError(f'private dependencies missing: {missing}')
        receipt = {'version': 2, 'final_sha256': FINAL_SHA, 'legacy_solo_sha256': LEGACY_SHA,
                   'wanted_poster_png_sha256': poster_texture.POSTER_SHA,
                   'copied': copied, 'camera_mapping': cameras, 'native_segment_calls': calls,
                   'scroll_bindings': scroll_bindings(resources[ANIMATION_TARGET]), 'unresolved_references': missing,
                   'preservation': 'FINAL art/geometry/UV/material values/texture pixels/scroll parameters unchanged; logical references and native scene/actor/camera framing adapted',
                   'runtime': 'unverified configured game/Prelude; native source and resource checks only'}
        resources[PRIVATE + 'manifest.json'] = (json.dumps(receipt, indent=2, sort_keys=True) + '\n').encode()
    return resources, receipt


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('final', type=Path)
    parser.add_argument('legacy_solo', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--contract', type=Path)
    parser.add_argument('--scroll-contract', type=Path)
    args = parser.parse_args()
    paths = [p for p in (args.output, args.contract, args.scroll_contract) if p]
    if len({p.resolve() for p in paths}) != len(paths) or any(p.resolve() in (args.final.resolve(), args.legacy_solo.resolve()) for p in paths) or args.output.exists():
        parser.error('choose separate output paths; immutable inputs and existing candidates cannot be overwritten')
    resources, receipt = convert(args.final, args.legacy_solo)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open('xb') as stream, zipfile.ZipFile(stream, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as pack:
        for name, data in sorted(resources.items()):
            info = zipfile.ZipInfo(name, (1980, 1, 1, 0, 0, 0));info.create_system = 3
            info.external_attr = 0o100644 << 16;info.compress_type = zipfile.ZIP_DEFLATED
            pack.writestr(info, data, compresslevel=9)
    if args.contract:
        args.contract.write_text(resource_header(resources))
    if args.scroll_contract:
        args.scroll_contract.write_text(scroll_header(receipt['scroll_bindings']))
    print(json.dumps({'output': str(args.output), 'size': args.output.stat().st_size,
                      'sha256': sha(args.output.read_bytes()), 'resources': len(resources),
                      'scroll_calls': receipt['native_segment_calls']}, indent=2))


if __name__ == '__main__':
    main()
