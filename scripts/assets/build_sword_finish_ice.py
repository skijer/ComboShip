#!/usr/bin/env python3
"""Pack the generated ice art into two small, seamless native I8 masks."""
import argparse
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "combo/render/sword_finish_ice_assets"


def seamless(image):
    pixels = image.load()
    width, height = image.size
    for y in range(height):
        value = (pixels[0, y] + pixels[width - 1, y]) // 2
        pixels[0, y] = pixels[width - 1, y] = value
    for x in range(width):
        value = (pixels[x, 0] + pixels[x, height - 1]) // 2
        pixels[x, 0] = pixels[x, height - 1] = value
    return image


def build(source=None, check=False):
    if not check:
        ASSETS.mkdir(parents=True, exist_ok=True)
    if source:
        # Keep the full ImageGen original separately. This bounded source is
        # sufficient to reproduce the 512-byte and 2048-byte runtime masks.
        image = Image.open(source).convert("L").resize((256, 128), Image.Resampling.LANCZOS)
        image.save(ASSETS / "frost-source.png", optimize=True)
    image = Image.open(ASSETS / "frost-source.png").convert("L")
    frost = image.resize((32, 16), Image.Resampling.LANCZOS)
    values = sorted(frost.tobytes())
    low, high = values[len(values) // 50], values[-len(values) // 50]
    frost = seamless(frost.point(lambda value: max(32, min(240, 32 + (value - low) * 208 // max(1, high - low)))))
    opacity = image.resize((64, 32), Image.Resampling.LANCZOS)
    opacity = seamless(opacity.point(lambda value: 150 + value * 90 // 255))
    textures = (("sSwordFinishIceFrostTex", "frost.i8.png", frost),
                ("sSwordFinishIceOpacityTex", "opacity.i8.png", opacity))
    lines = ["// Generated by scripts/assets/build_sword_finish_ice.py; native I8 bytes.",
             "#pragma once", "#include <cstdint>", "", "// clang-format off"]
    for name, filename, texture in textures:
        path = ASSETS / filename
        if check:
            with Image.open(path) as current:
                if current.mode != texture.mode or current.size != texture.size or current.tobytes() != texture.tobytes():
                    raise SystemExit(f"Generated ice texture is stale: {path}")
        else:
            texture.save(path, optimize=True)
        data = texture.tobytes()
        lines.append(f"alignas(8) static const uint8_t {name}[{len(data)}] = {{")
        lines.extend("    " + ", ".join(f"0x{value:02X}" for value in data[start:start + 16]) + ","
                     for start in range(0, len(data), 16))
        lines += ["};", ""]
    lines.append("// clang-format on\n")
    path = ROOT / "combo/render/SwordFinishIceData.h"
    header = "\n".join(lines)
    if check:
        if path.read_text() != header:
            raise SystemExit(f"Generated ice header is stale: {path}")
    else:
        path.write_text(header)
    print(("Validated" if check else "Packed") +
          " seamless finish ice: 32x16 I8 frost + 64x32 I8 opacity, 2560 bytes total")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--source", type=Path)
    group.add_argument("--check", action="store_true", help="Validate generated pixels and header without writing files")
    args = parser.parse_args()
    build(args.source, args.check)
