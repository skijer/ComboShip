#!/usr/bin/env python3
"""Import preserved spin designs into private, coexisting native-host resources.

Requires the unchanged input archives identified below. No source archive or
shared gameplay_keep resource is rewritten. --check verifies shipped outputs;
--inputs DIR --check also reproduces them from those exact archived inputs.
"""
from pathlib import Path
import argparse
import hashlib
import json
import math
import struct
import zipfile

from build_din_fire_shield import crc64, header

ROOT = Path(__file__).resolve().parents[2]
MANIFEST = ROOT / "tools/spin_styles/manifest.json"
INPUTS = {
    "fire": ("zzzz_MM_Spin_Fire_Reborn_HD_POC2.o2r", "96543e561f2d59d38503c9225e2b28d001d1f44cdc022cbbe15df6d7a7ba83f1"),
    "lightning": ("zzzz_MM_Spin_Lightning_HD_POC1(1).o2r", "e87da3e71eafee2998dfb421c1abec47b636c33dfea0d81761a1299b7386d091"),
    "arcane": ("zzzz_MM_Spin_Arcane_Level2_Circle_POC4.o2r", "794741cfcbfa39d4307be93da5d00681d079c05cfb534e4bdc37d758cdbc99e1"),
    "astral_mm": ("zzzz_MM_Spin_Astral_Rupture_HD_POC1.o2r", "5ebff2a2630a220f94e719dd30869d689505c3881fe4a0f0fb7c736b1427a9e3"),
    "astral_soh": ("zzzz_Spin_Astral_Rupture_HD_Alt_POC1.o2r", "ee15f95b931c51bbf5388372470b980c2a430229a24a0e8341ab3c0d5b9e4a9c"),
}
STYLES = ("fire", "ice", "light", "lightning", "arcane", "astral", "dark_energy")
ALIASES = {
    "gSpinAttackDiskDL": "disk_regular", "gSpinAttackCylinderDL": "cylinder_regular",
    "gGreatSpinAttackDiskDL": "disk_great", "gGreatSpinAttackCylinderDL": "cylinder_great",
    "gSpinAttack1DL": "disk_regular", "gSpinAttack2DL": "cylinder_regular",
    "gSpinAttack3DL": "disk_great", "gSpinAttack4DL": "cylinder_great",
    "gSpinAttackChargingDL": "charge",
    "gSpinAttack1Tex": "burst0", "gSpinAttack2Tex": "burst1",
    "gSpinAttackCharging1Tex": "charge0", "gSpinAttackCharging2Tex": "charge1",
    "gTorchFlameTex": "burst0", "gEffUnknown1Tex": "burst1",
    "gFlameWall1Tex": "charge0", "gFlameWall2Tex": "charge1",
}
EXPANDED = (0x20, 0x31, 0x32, 0x33, 0x36, 0x37, 0x39)
ASTRAL_LEGACY_CHARGE_VERTEX = 0xF983F61EF6E87EC3
ASTRAL_CHARGE_VERTEX = "alt/objects/gameplay_keep/spin_astral_rupture_poc1/gSpinChargeVtx"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def command_shape(raw):
    result, i = [], 72
    while i < len(raw):
        w0, w1 = struct.unpack_from("<II", raw, i)
        result.append((w0, w1))
        i += 16 if w0 >> 24 in EXPANDED else 8
    return result


def dependency_header(manifest):
    lines = ["/* Generated by scripts/assets/build_spin_style_resources.py. */", "// clang-format off",
             "#ifndef COMBO_SPIN_ATTACK_STYLE_DEPENDENCIES_H", "#define COMBO_SPIN_ATTACK_STYLE_DEPENDENCIES_H"]
    for host in ("mm", "soh"):
        lines += ["#ifdef CW_SPIN_HOST_MM" if host == "mm" else "#else"]
        for style in STYLES:
            resources = manifest["styles"][style][host]["resources"]
            lines += [f"static const char* const sSpinDeps_{style}[] = {{"]
            lines += ['    "' + path + '",' for path in resources]
            lines += ["};"]
    lines += ["#endif", "static inline const char* const* CwSpinStyle_Dependencies(CwSpinStyle style, size_t* count) {",
              "    switch (style) {"]
    for index, style in enumerate(STYLES, 1):
        lines += [f"        case {index}: *count = sizeof(sSpinDeps_{style}) / sizeof(sSpinDeps_{style}[0]); return sSpinDeps_{style};"]
    lines += ["        default: *count = 0; return NULL;", "    }", "}", "#endif", "// clang-format on", ""]
    return "\n".join(lines).encode()


def texture(raw):
    version = struct.unpack_from("<I", raw, 8)[0]
    typ, width, height = struct.unpack_from("<III", raw, 64)
    assert typ == 6 and 0 < width <= 4096 and 0 < height <= 4096
    if version == 0:
        length = struct.unpack_from("<I", raw, 76)[0]
        assert len(raw) == 80 + length and length == width * height
        pixels = b"".join(bytes((v, v, v, v)) for v in raw[80:])
    else:
        flags, sx, sy, length = struct.unpack_from("<IffI", raw, 76)
        assert version == 1 and flags == 3 and sx == sy == 1.0
        assert len(raw) == 92 + length and length == width * height * 4
        return raw  # Preserve exact authored pixels and already-correct metadata.
    h = bytearray(header(0x4F544558))
    struct.pack_into("<I", h, 8, 1)
    return bytes(h) + struct.pack("<IIIIffI", 6, width, height, 3, 1.0, 1.0, len(pixels)) + pixels


def material_combine(w0, w1, dark=False):
    # Use texture alpha for the RGB ramp: some preserved maps have solid-white
    # RGB even in transparent pixels. Keep every native alpha-mux bit intact.
    # Dark reverses the ramp for a crimson core inside violet outer wisps.
    a, b = (5, 3) if dark else (3, 5)  # ENVIRONMENT / PRIMITIVE
    rgb0 = (15 << 20) | (31 << 15) | (15 << 5) | 31
    rgb1 = (15 << 28) | (15 << 24) | (7 << 15) | (7 << 6)
    return ((w0 & ~rgb0) | (a << 20) | (8 << 15) | (a << 5) | 8,
            (w1 & ~rgb1) | (b << 28) | (b << 24) | (b << 15) | (b << 6))


def remap_dl(raw, names, mapping, style):
    assert raw[64] == 4 and len(raw) % 8 == 0
    result = bytearray(raw)
    i = 72
    while i < len(raw):
        w0, w1 = struct.unpack_from("<II", raw, i)
        if w0 >> 24 == 0xFC:
            struct.pack_into("<II", result, i, *material_combine(w0, w1, style == "dark_energy"))
        i += 8
        if w0 >> 24 in EXPANDED:
            hi, lo = struct.unpack_from("<II", raw, i)
            old = names[(hi << 32) | lo]
            new = crc64(mapping[old])
            struct.pack_into("<II", result, i, new >> 32, new & 0xFFFFFFFF)
            i += 8
        if w0 >> 24 == 0xDF:
            assert i == len(raw)
    return bytes(result)


def dark_vertices(raw):
    result = bytearray(raw)
    typ, count = struct.unpack_from("<II", raw, 64)
    assert typ == 25 and len(raw) == 72 + count * 16
    for i in range(count):
        offset = 72 + i * 16
        x, y, z = struct.unpack_from("<hhh", raw, offset)
        angle = math.atan2(z, x)
        # Distort the existing wisps coherently; shared seam vertices stay shared.
        factor = 1.0 + 0.065 * math.sin(angle * 7)
        struct.pack_into("<hhh", result, offset, round(x * factor),
                         round(y + 75 * math.sin(angle * 5)), round(z * factor))
    return bytes(result)


def generate(directory):
    archives, source_info = {}, {}
    for key, (filename, digest) in INPUTS.items():
        path = directory / filename
        assert sha(path.read_bytes()) == digest, f"Unexpected input: {filename}"
        with zipfile.ZipFile(path) as z:
            assert z.testzip() is None
            entries = {n: z.read(n) for n in z.namelist() if not n.endswith("/")}
        archives[key] = entries
        source_info[key] = {"filename": filename, "sha256": digest,
                            "entries": {n: sha(b) for n, b in entries.items()}}
    outputs = {}
    manifest = {"inputs": source_info, "styles": {s: {} for s in STYLES}, "outputs": {}}
    # The preserved OoT pack refers to an unbundled legacy charging vertex hash.
    # Its complete charge command stream matches MM's, including its 14-vertex
    # layout. Import that exact authored array into our private standalone graph.
    charge_root = "alt/objects/gameplay_keep/gSpinAttackChargingDL"
    assert command_shape(archives["astral_soh"][charge_root]) == command_shape(archives["astral_mm"][charge_root])
    charge_vertices = archives["astral_mm"][ASTRAL_CHARGE_VERTEX]
    assert struct.unpack_from("<II", charge_vertices, 64) == (25, 14)
    archives["astral_soh"][ASTRAL_CHARGE_VERTEX] = charge_vertices
    manifest["repairs"] = {"astral_soh_charge_vertex": {
        "legacy_hash": f"{ASTRAL_LEGACY_CHARGE_VERTEX:016x}",
        "donor": "astral_mm", "entry": ASTRAL_CHARGE_VERTEX,
        "sha256": sha(charge_vertices), "command_streams_equal_except_resource_hashes": True}}
    for host in ("soh", "mm"):
        host_outputs = {}
        for style in STYLES:
            donor = ("astral_" + host if style == "astral" else
                     "arcane" if style == "dark_energy" else
                     "fire" if style in ("ice", "light") else style)
            entries = archives[donor]
            # Each game's preserved Astral art differs. Distinct names prevent
            # cross-game resource routing from selecting the other host's pack.
            resource_style = style + "_" + host if style == "astral" else style
            prefix = f"objects/combo_spin/{resource_style}/"
            mapping = {}
            for old in entries:
                relative = old.removeprefix("alt/objects/gameplay_keep/")
                mapping[old] = prefix + ALIASES.get(relative, relative)
            assert len(set(mapping.values())) == len(mapping)
            names = {crc64(old): old for old in entries}
            if donor == "astral_soh":
                names[ASTRAL_LEGACY_CHARGE_VERTEX] = ASTRAL_CHARGE_VERTEX
            for old, raw in entries.items():
                kind = struct.unpack_from("<I", raw, 4)[0]
                if kind == 0x4F444C54:
                    raw = remap_dl(raw, names, mapping, style)
                elif kind == 0x4F544558:
                    raw = texture(raw)
                elif style == "dark_energy" and kind == 0x4F415252:
                    raw = dark_vertices(raw)
                host_outputs[mapping[old]] = raw
            # Ice uses the crystal/sigil surface; Light uses the celestial sigil.
            if style in ("ice", "light"):
                astral = archives["astral_mm"]
                sigil = "gAstralSigil2Tex" if style == "ice" else "gAstralSigil1Tex"
                selected = next(raw for n, raw in astral.items() if n.endswith("/" + sigil))
                host_outputs[prefix + "burst1"] = texture(selected)
            manifest["styles"][style][host] = {"donor": donor,
                "resources": sorted(mapping.values()),
                "roots": [prefix + n for n in ("charge", "disk_regular", "cylinder_regular", "disk_great", "cylinder_great")]}
        for relative, raw in host_outputs.items():
            outputs[ROOT / host / "assets/custom" / relative] = raw
        manifest["outputs"][host] = {name: sha(raw) for name, raw in sorted(host_outputs.items())}
    outputs[MANIFEST] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode()
    outputs[ROOT / "combo/render/SpinAttackStyleDependencies.h"] = dependency_header(manifest)
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--inputs", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        from prepare_spin_styles import prepare
        prepare()
    if args.inputs:
        outputs = generate(args.inputs)
        if not args.check and MANIFEST.exists():
            previous = json.loads(MANIFEST.read_text())
            for host, entries in previous["outputs"].items():
                for name in entries:
                    assert name.startswith("objects/combo_spin/")
                    old = ROOT / host / "assets/custom" / name
                    if old not in outputs:
                        old.unlink(missing_ok=True)
        for path, data in outputs.items():
            if args.check:
                assert path.read_bytes() == data, path
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_bytes(data)
    else:
        assert args.check, "Provide --inputs with the preserved source archives"
        manifest = json.loads(MANIFEST.read_text())
        assert (ROOT / "combo/render/SpinAttackStyleDependencies.h").read_bytes() == dependency_header(manifest)
        for host, entries in manifest["outputs"].items():
            for name, digest in entries.items():
                assert sha((ROOT / host / "assets/custom" / name).read_bytes()) == digest, name
    print("PASS deterministic private spin resources" if args.check else "Generated private spin resources")


if __name__ == "__main__":
    main()
