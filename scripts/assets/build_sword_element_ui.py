#!/usr/bin/env python3
"""Compile the approved elemental art and shipped Montserrat into safe native UI textures.

No archive or runtime mod is required. Each 64x64 RGBA icon is submitted as four
32x32/4096-byte tiles; IA8 font strips are rasterized at twice their logical size.
The source PNGs are preserved verbatim and identified in the generated manifest.
"""
from pathlib import Path
import argparse
import hashlib
import json

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
ASSETS = ROOT / "combo/render/sword_element_ui_assets"
FONT = ROOT / "soh/assets/custom/fonts/Montserrat-Regular.ttf"
ART_HEADER = ROOT / "combo/render/sword_element_ui_art_data.h"
TYPE_HEADER = ROOT / "combo/render/sword_element_ui_type_data.h"
TEXT = {
    "Title": ("Sword element", 20),
    "Subtitle": ("Choose an affinity", 12),
    "None": ("None", 18), "Fire": ("Fire", 18),
    "Ice": ("Ice", 18), "Light": ("Light", 18),
    "Active": ("ACTIVE", 10), "Locked": ("LOCKED", 10),
    "Select": ("Select", 12), "Arrows": ("\u2039 \u203a", 20),
    "A": ("A", 12), "B": ("B", 12),
    "Apply": ("Apply", 12), "Back": ("Back", 12),
}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def c_bytes(data, indent="    "):
    return "\n".join(indent + ", ".join(f"0x{x:02x}" for x in data[i:i + 24]) + ","
                     for i in range(0, len(data), 24))


def ia8(alpha):
    # IA8 = I4/A4, with white intensity and antialiased coverage.
    return bytes(0xf0 | ((x + 8) // 17) for x in alpha.tobytes())


def make_type(text, size):
    font = ImageFont.truetype(str(FONT), size)
    left, top, right, bottom = font.getbbox(text)
    width = (right - left + 9) // 8 * 8
    height = bottom - top + 4
    canvas = Image.new("L", (width, height))
    ImageDraw.Draw(canvas).text((2 - left, 2 - top), text, font=font, fill=255)
    assert width * height <= 4096, (text, canvas.size)
    return canvas


def outputs():
    manifest = {"font": {"path": str(FONT.relative_to(ROOT)), "sha256": sha(FONT)},
                "physical_icon_size": [64, 64], "logical_icon_size": [32, 32],
                "native_tile_size": [32, 32], "maximum_texture_load_bytes": 4096,
                "font_physical_to_logical_scale": 2, "sources": {}, "labels": {}}
    art = ["/* Generated by scripts/assets/build_sword_element_ui.py. */", "// clang-format off",
           "#ifndef SWORD_ELEMENT_UI_ART_DATA_H", "#define SWORD_ELEMENT_UI_ART_DATA_H",
           "#include <stdint.h>",
           "enum { SWORD_ELEMENT_UI_ICON_SIZE = 64, SWORD_ELEMENT_UI_TILE_SIZE = 32 };",
           "typedef struct { uint64_t before; uint8_t pixels[32 * 32 * 4]; uint64_t after; } SwordElementUiRgbaTile;",
           "#define SWORD_ELEMENT_UI_CANARY UINT64_C(0xc5317b2a6f409de8)"]
    for name in ("Fire", "Ice", "Light"):
        source = ASSETS / (name.lower() + "-source.png")
        image = Image.open(source).convert("RGBA")
        manifest["sources"][name.lower()] = {"path": str(source.relative_to(ROOT)),
                                                "sha256": sha(source), "size": list(image.size)}
        # Keep a transparent edge for clamped bilinear sampling.
        icon = Image.new("RGBA", (64, 64))
        icon.alpha_composite(image.resize((62, 62), Image.Resampling.LANCZOS), (1, 1))
        art += [f"static const SwordElementUiRgbaTile sSwordElementUi{name}Art[4] = {{"]
        for y in (0, 32):
            for x in (0, 32):
                pixels = icon.crop((x, y, x + 32, y + 32)).tobytes()
                art += ["    { SWORD_ELEMENT_UI_CANARY, {", c_bytes(pixels, "        "),
                        "    }, SWORD_ELEMENT_UI_CANARY },"]
        art += ["};"]
    art += ["#endif", "// clang-format on", ""]
    types = ["/* Generated from the repository's bundled Montserrat font. */", "// clang-format off",
             "#ifndef SWORD_ELEMENT_UI_TYPE_DATA_H", "#define SWORD_ELEMENT_UI_TYPE_DATA_H",
             "#include <stdint.h>", "#include \"align_asset_macro.h\"",
             "typedef struct { const uint8_t* pixels; uint16_t width, height; } SwordElementUiMask;"]
    masks = {name: make_type(text, size) for name, (text, size) in TEXT.items()}
    # The native IA8 load path transfers 16-bit units, so even this solid strip
    # has padded storage rather than asking the renderer to read a one-byte image.
    masks["Solid"] = Image.new("L", (8, 1), 255)
    # A nine-slice panel, circular controller chips and a compact padlock all share IA8 rendering.
    scale = 4
    for name, draw in (
        ("Round", lambda d: d.rounded_rectangle((0, 0, 32 * scale - 1, 32 * scale - 1), 10 * scale, fill=255)),
        ("Circle", lambda d: d.ellipse((0, 0, 32 * scale - 1, 32 * scale - 1), fill=255)),
        ("Lock", lambda d: (d.rounded_rectangle((7 * scale, 14 * scale, 25 * scale, 28 * scale), 3 * scale, fill=255),
                             d.arc((10 * scale, 3 * scale, 22 * scale, 23 * scale), 180, 360, fill=255, width=3 * scale))),
    ):
        canvas = Image.new("L", (32 * scale, 32 * scale))
        draw(ImageDraw.Draw(canvas))
        masks[name] = canvas.resize((32, 32), Image.Resampling.LANCZOS)
    for name, mask in masks.items():
        data = ia8(mask)
        types += [f"static const ALIGN_ASSET(8) uint8_t sSwordElementUi{name}Pixels[{len(data)}] = {{",
                  c_bytes(data), "};",
                  f"static const SwordElementUiMask sSwordElementUi{name} = {{ sSwordElementUi{name}Pixels, {mask.width}, {mask.height} }};"]
        if name in TEXT:
            manifest["labels"][name] = {"text": TEXT[name][0], "physical_size": list(mask.size),
                                         "logical_size": [mask.width / 2, mask.height / 2], "format": "IA8"}
    types += ["#endif", "// clang-format on", ""]
    return {ART_HEADER: "\n".join(art), TYPE_HEADER: "\n".join(types),
            ASSETS / "manifest.json": json.dumps(manifest, indent=2) + "\n"}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            assert path.read_text() == content, f"Regenerate {path.relative_to(ROOT)}"
        else:
            path.write_text(content)
    print("sword element UI textures: " + ("deterministic outputs PASS" if args.check else "generated"))


if __name__ == "__main__":
    main()
