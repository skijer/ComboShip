inline const Entry* Find(const char* cvar, const char* label = nullptr) {
    if (cvar && cvar[0]) {
        for (const auto& entry : kControls) {
            if (std::strcmp(cvar, entry.key) == 0)
                return &entry;
        }
        return nullptr;
    }
    if (label) {
        for (const auto& entry : kSections) {
            if (std::strcmp(label, entry.key) == 0)
                return &entry;
        }
    }
    return nullptr;
}

inline ImVec4 Accent(Kind kind) {
    return kind == Kind::New ? ImVec4(1.0f, 0.82f, 0.36f, 1.0f) : ImVec4(0.40f, 0.88f, 1.0f, 1.0f);
}

// Keep the native caption and ID so live toggles retain selection and tab width.
// Restore text styling before the caller draws the selected tab's contents.
inline bool BeginTabItem(const char* label, bool enabled) {
    const Entry* entry = enabled ? Find(nullptr, label) : nullptr;
    if (!entry)
        return ImGui::BeginTabItem(label);
    ImGui::PushStyleColor(ImGuiCol_Text, Accent(entry->kind));
    const bool open = ImGui::BeginTabItem(label);
    ImGui::PopStyleColor();
    if (ImGui::IsItemHovered(ImGuiHoveredFlags_AllowWhenDisabled))
        ImGui::SetTooltip("%s", entry->note);
    return open;
}

// Styling never submits an item or changes layout/last-item state. The native
// widget owns its caption, tooltip and navigation. Restore color on every exit.
class Scope {
  public:
    Scope(const char* cvar, const char* label, bool enabled, bool disabled = false) {
        const Entry* entry = enabled ? Find(cvar, label) : nullptr;
        if (!entry || disabled)
            return;
        ImGui::PushStyleColor(ImGuiCol_Text, Accent(entry->kind));
        mActive = true;
    }
    ~Scope() {
        if (mActive)
            ImGui::PopStyleColor();
    }
    Scope(const Scope&) = delete;
    Scope& operator=(const Scope&) = delete;

  private:
    bool mActive = false;
};
